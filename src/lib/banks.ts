/** 공시·사용자 입력의 은행 이름을 앱의 은행 이름으로 맞춘다 ('주식회사' 같은 회사 형태는 뗀다). */
export function canonicalBank(name: string): string {
  const trimmed = name.replace(/주식회사|\(주\)|㈜/g, '').replace(/\s+/g, '');
  return ALIASES[trimmed] ?? trimmed;
}
